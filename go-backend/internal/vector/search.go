// SearchOptions controls optional pipeline stages for a Search call.
// LongContextTopK is the upper cap on the SearchResult chunk count
// when SearchOptions.LongContextMode is true. The chat layer applies
// its own token-budget truncation downstream, so this number only
// needs to be large enough to overflow any sensible budget (a 200-
// chunk pool at ~500 tokens each is already ~100 k tokens, the
// review's documented global-synthesis ceiling). Operators wanting
// a smaller / larger cap should adjust ChatLongContextMaxTokens,
// which gates the chat-side truncation; raising this constant
// without raising the budget just wastes the wider DB query.
const LongContextTopK = 200

type SearchOptions struct {
	Enhance    string            // "rewrite", "expand", "spell", or ""
	Filters    map[string]string // metadata filters (currently reserved for future use)
	FileIDs    []string          // restrict search to specific file IDs
	SkipCache  bool              // reserved for cache bypass
	HyDE       bool              // generate hypothetical answer before embedding
	MultiQuery bool              // generate alternative query phrasings in parallel
	// StepBack enables step-back retrieval: a single broader query is
	// generated by the LLM and run as an extra vector search whose results
	// fold into the RRF fusion stage. Plugs into the same `extraLists`
	// path as MultiQuery but generates a higher-level abstraction rather
	// than a paraphrase. The search code internally gates step-back on
	// QueryType == QueryTypeComplexReasoning, so setting StepBack on
	// other query types is a no-op (recorded as skipped_route).
	StepBack bool
	// Grade enables CRAG-style relevance grading after retrieval. When set,
	// the final returned chunks each carry a Grade and the result reports
	// how many of each verdict were seen. The grader runs on the trimmed
	// top-K result so it never wastes tokens on chunks that would be
	// filtered out anyway.
	Grade bool
	// GraderModel optionally pins the chat model used by the relevance
	// grader (typically a small/fast model). Empty = resolver default.
	GraderModel string
	// ModelOverride names an alternative chat model to use for auxiliary LLM
	// calls during retrieval (HyDE, MultiQuery). Empty = use resolver default.
	// Deep chat sets this to the configured enrichment model so its planning
	// calls go to a cheaper/faster model while the final answer stays on the
	// main chat model.
	ModelOverride string
	// QueryType classifies the query for downstream adaptive logic
	// (Phase 2 §A: per-query-type rerank_blend_alpha) and per-query-type
	// telemetry. Empty string is normalized to QueryTypeUnknown by the
	// search pipeline; callers should classify upstream when possible so
	// the label reflects the request as it entered the system.
	QueryType string
	// SubQueries is a caller-supplied list of additional queries to run as
	// parallel embedding searches and fold into RRF fusion via the same
	// extraLists path used by MultiQuery and StepBack. Non-empty SubQueries
	// is the Plan stage's signal that decomposition has already been done
	// upstream (RunPlanExecuteChat); when set, MultiQuery / StepBack / HyDE
	// should typically be left off by the caller to avoid double-fanout.
	//
	// Cap: caller is responsible for capping — no internal max here.
	// Each sub-query incurs one embedding call + one ANN search.
	SubQueries []string

	// GraphChunkIDs is a caller-supplied list of chunk IDs the AP-C4
	// graph router resolved from the KB's knowledge graph
	// (kg.Store.LookupSubgraph). When non-empty, the search service
	// fetches those chunks from the dim-keyed chunk table and folds
	// them into RRF via the same extraLists path used by SubQueries /
	// MultiQuery / StepBack. The graph contribution inherits the
	// vector RRF weight (no separate knob in v1).
	//
	// Cap: caller is responsible for capping (chat layer enforces
	// chat_graph_routing_max_chunks, default 15).
	GraphChunkIDs []string

	// HyPESearch enables the HyPE arm: the query embedding is matched
	// against ingest-time hypothetical-question embeddings in
	// chunk_hype_questions_<dim>; matched questions resolve to their
	// parent chunks, which fold into RRF via the same extraLists path as
	// GraphChunkIDs. No-op (fail-open) when the HyPE table is missing/empty.
	// Set by the chat layer from hype_search_enabled; never by users.
	HyPESearch bool

	// NodeKindFilter is the Phase F (RAPTOR) eval-only retrieval
	// filter. When non-empty (only "leaf" or "summary" are accepted),
	// the primary vector + keyword SELECTs add `AND node_kind = $N`
	// to the WHERE clause. Used by `./cmd/eval/eval --node-kind …`
	// to measure leaves-only vs. summary-included recall in
	// ablations. The public chat handler never sets this — production
	// retrieval always sees both kinds in one pool.
	NodeKindFilter string

	// LongContextMode is the T2-1 System-2 routing signal. When
	// true, Search() raises top-k to LongContextTopK (or the
	// admin-configured `chat_longcontext_top_k`), skips MMR, skips
	// score-drop filtering, and skips parent-child swap — every
	// operation whose purpose is to narrow the candidate pool. The
	// resulting wide chunk pool is what enables a long-context
	// answer pass (the chat layer is responsible for not over-
	// stuffing the model's window; see ChatLongContextMaxTokens).
	//
	// Set by the chat layer via ShouldRouteLongContext, never by
	// users. The query-time-only flag means a cached SearchResult
	// from normal-mode is NOT poisoned by long-context shape and
	// vice-versa (the shape hash differs).
	LongContextMode bool
}

// Query-type classification labels surfaced via Prometheus and structured
// logs. The set matches the eval harness's per-query-type breakdown so
// offline eval and production telemetry are directly comparable.
const (
	QueryTypeLookup           = "lookup"
	QueryTypeEnumeration      = "enumeration"
	QueryTypeComplexReasoning = "complex_reasoning"
	QueryTypeUnknown          = "unknown"
)

// SearchResult is the output of a Search call.
type SearchResult struct {
	Chunks            []SearchChunk `json:"chunks"`
	EnhancedQuery     string        `json:"enhancedQuery,omitempty"`
	FromCache         bool          `json:"fromCache,omitempty"`
	ContextWindowSize int           `json:"-"`
	TableName         string        `json:"-"`
	// Graded reports whether the relevance grader actually ran on this
	// result (controlled by SearchOptions.Grade). False when CRAG was
	// disabled or the grader silently failed open.
	Graded bool `json:"graded,omitempty"`
	// KeywordMatchFileIDs is the distinct set of file IDs that BM25
	// returned (in rank order). Used by downstream enumeration extraction
	// as pre-seeded candidates — BM25's exact-match signal anchors the
	// LLM's per-chunk yes/no decision against under-recall on templated
	// content where cross-encoder rerankers systematically downrank the
	// exact evidence chunks.
	KeywordMatchFileIDs []string `json:"-"`
}

// SearchChunk represents a single retrieved document chunk with scoring detail.
type SearchChunk struct {
	ID      string `json:"id"`
	Content string `json:"content"`
	// ContextualPrefix is the 1-sentence LLM-generated document-level context
	// attached to this chunk during ingestion (Anthropic-style Contextual
	// Retrieval). It's used for LLM prompt assembly — surfacing this to the
	// model turns an otherwise context-free chunk (e.g. a team list row)
	// into identifiable evidence ("... this passage lists the team of
	// project Alpha"). Empty when enrichment was disabled at ingestion.
	// Not persisted to the UI-facing MessageSource — the user still sees
	// the original content only.
	ContextualPrefix string         `json:"-"`
	FileID           string         `json:"fileId"`
	FileName         string         `json:"fileName"`
	Metadata         map[string]any `json:"metadata"`
	Score            float64        `json:"score"`
	VectorScore      float64        `json:"vectorScore,omitempty"`
	KeywordRank      float64        `json:"keywordRank,omitempty"`
	RerankScore      float64        `json:"rerank_score,omitempty"`
	// Grade is set by the CRAG-style relevance grader (see ai.GradeRelevance)
	// when SearchOptions.Grade is true. Empty when grading is disabled.
	Grade ai.Grade `json:"grade,omitempty"`
	// ParentChunkID is the FK to document_chunk_parents.id when this row
	// is a Phase 3 §D parent-child child chunk; nil for legacy flat rows.
	// The retrieval-time swap rewrites Content / ContextualPrefix from the
	// parent before this struct surfaces to chat-context assembly, so by
	// the time downstream code reads Content the swap is complete. The
	// field stays on the struct for ExpandNeighbors's NULL check and for
	// debugging / tracing.
	ParentChunkID *string `json:"-"`
	// NodeKind is "leaf" for ordinary chunks and "summary" for Phase F
	// RAPTOR-built summary nodes. Empty == "leaf". Surfaced to the
	// answer prompt via renderSourceHeader so the LLM knows the
	// snippet is paraphrased prose.
	NodeKind string `json:"nodeKind,omitempty"`
	// TreeLevel is 0 for leaves, 1..N for RAPTOR summaries.
	TreeLevel int `json:"treeLevel,omitempty"`
}

