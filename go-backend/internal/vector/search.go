// ---------------------------------------------------------------------------
// Per-operation timeouts
// ---------------------------------------------------------------------------
//
// The HTTP server's WriteTimeout caps the whole response (≥120 s for chat).
// Without per-op deadlines, a single stalled sidecar call (rerank, grader,
// embed) can hold the connection for the full server-wide budget. Each AI
// call below gets its own context.WithTimeout so the search pipeline fails
// fast when one stage degrades — letting the chat layer's fail-open paths
// (rerank skipped, CRAG fail-opens to "ambiguous", search returns empty)
// produce a usable answer instead of a connection-level timeout.
//
// Embed/rerank are the longest tail (cross-encoder over many docs); enhance
// (rewrite/expand/spell) and grade are short structured calls.
const (
	embedTimeout          = 30 * time.Second
	rerankTimeout         = 30 * time.Second
	enhanceQueryTimeout   = 15 * time.Second
	gradeRelevanceTimeout = 30 * time.Second
)

