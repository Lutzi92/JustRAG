// Searcher is the contract callers depend on for hybrid retrieval. The
// concrete *SearchService satisfies it; consumers (chat orchestrators, MCP
// tools, eval harness, contentgen, publicapi, …) accept this interface so
// they can be tested with fakes that don't need a pgxpool. This is the
// canonical interface — package-local re-declarations should alias here.
//
// ExpandNeighbors is included even though most callers only need Search: it
// returns []SearchChunk (an exported type) instead of forcing the underlying
// NeighborFetcher contract on consumers, which uses an unexported row type.
type Searcher interface {
	Search(ctx context.Context, kbID, query string, limit int, opts SearchOptions) (*SearchResult, error)
	ExpandNeighbors(ctx context.Context, chunks []SearchChunk, windowSize int, tableName, kbID string) []SearchChunk
}

// Compile-time assertion that the production SearchService implements
// Searcher. Catches drift between the interface and its sole production
// implementation.
var _ Searcher = (*SearchService)(nil)

// SearchService orchestrates the hybrid search pipeline (vector + keyword,
// optional HyDE, optional multi-query, RRF fusion, optional reranking).
type SearchService struct {
	vectorDB       *pgxpool.Pool
	mainDB         *pgxpool.Pool
	aiResolver     *ai.ConfigResolver
	siteConfig     SiteConfigReader
	embeddingCache *ai.EmbeddingCache
	// chunkSvc is the parent-chunk lookup target for the Phase 3 §D
	// retrieval-time swap. Optional — when nil, the swap step is a no-op
	// and rows with non-nil ParentChunkID still surface their child
	// content (defensive fallback for tests / call sites that haven't
	// wired the dependency yet).
	chunkSvc *ChunkService
	// hype is the HyPEStore used for the query-time HyPE arm. When non-nil
	// and opts.HyPESearch is set, Search() matches the query embedding
	// against ingest-time hypothetical-question embeddings and folds the
	// resolved parent chunks into RRF via the extraLists path.
	hype *HyPEStore
	// queryCache is the optional semantic query-result cache. When non-nil
	// and enabled via site_config (`query_cache_enabled`), Search() consults
	// it before running the embed/search pipeline and stores the assembled
	// SearchResult on the success path. nil disables the feature with zero
	// overhead — the lookup-then-bypass block becomes a single field check.
	queryCache *QueryCache
	// rerankDefaultNoticeOnce gates a one-shot operator notice emitted the
	// first time a search runs with a reranker active AND no explicit
	// `rerank_blend_alpha` site_config entry. Pre-existing deployments had
	// an implicit 50/50 blend; the new default (1.0, pure reranker) is a
	// silent behaviour change for those, so we surface it at runtime.
	rerankDefaultNoticeOnce sync.Once
	// kbTableCache memoises kb_id → chunks-table-name for the AP-B1
	// keyword_search / chunk_read / document_outline tools. Defined in
	// keyword_search.go; declared here so the struct stays the
	// canonical "things SearchService owns" view.
	kbTableCache kbTableCache

	// siteConfigCache memoizes loadSiteConfig output for siteConfigCacheTTL.
	// Site config is global (no per-KB key) and only changes when an admin
	// edits the panel — fetching it on every Search wastes one DB round-trip
	// per request. The TTL is short enough that operator edits propagate
	// without an explicit invalidation step.
	//
	// atomic.Pointer (not RWMutex) because the cache is a single value read
	// on every Search call and refreshed at most once per TTL window. An
	// RWMutex still costs a CAS pair on RLock/RUnlock and bounces the lock's
	// cache line between cores under heavy concurrency; an atomic load is
	// wait-free and reads a single immutable snapshot. The refresh path uses
	// siteConfigSF to coalesce concurrent refresh attempts into one DB
	// round-trip per TTL window — singleflight (not a plain mutex) so the
	// losing goroutines block on a channel, the DB call isn't held under a
	// lock, and ctx cancellation on the in-flight loader propagates back to
	// waiters cleanly.
	siteConfigCache atomic.Pointer[siteConfigCacheEntry]
	siteConfigSF    singleflight.Group

	// kbLangCache memoizes per-KB language strings. KB language is set at KB
	// creation and effectively never changes; a long TTL is safe. Same
	// atomic.Pointer + singleflight pattern as siteConfigCache above: the
	// hot read is a wait-free atomic load + a map lookup, and concurrent
	// refreshers coalesce onto one DB round-trip per TTL window. The
	// snapshot loads every KB's language in one SELECT (the table is tiny
	// — typically O(10-100) rows), so per-KB lookups never touch the DB
	// in the steady state. KBs that landed after the last refresh fall
	// through to a single-row QueryRow without poisoning the snapshot;
	// the next TTL-driven refresh picks them up.
	kbLangCachePtr atomic.Pointer[kbLangSnapshot]
	kbLangSF       singleflight.Group

	feedback FeedbackReader // nil when the feedback loop is unwired/disabled
}

const (
	siteConfigCacheTTL = 10 * time.Second
	kbLangCacheTTL     = 10 * time.Minute
)

// kbLangSnapshot is the immutable per-KB language map handed to readers
// via atomic.Pointer. Built once per TTL window from a single SELECT.
type kbLangSnapshot struct {
	langs     map[string]string
	expiresAt time.Time
}

// siteConfigCacheEntry is the immutable snapshot stored in the atomic
// pointer. KBVectorConfig is a value type with no internal pointers, so
// snapshotting it once and handing readers a *const view is race-free
// without any locking on the read path.
type siteConfigCacheEntry struct {
	cfg       KBVectorConfig
	expiresAt time.Time
}

// Option configures a SearchService at construction time.
type Option func(*SearchService)

// WithEmbeddingCache attaches an EmbeddingCache so repeated queries skip the
// embedding API.
func WithEmbeddingCache(c *ai.EmbeddingCache) Option {
	return func(s *SearchService) { s.embeddingCache = c }
}

// WithSiteConfigReader attaches a SiteConfigReader so the search pipeline can
// load admin-tuned thresholds from the site_configs table.
func WithSiteConfigReader(r SiteConfigReader) Option {
	return func(s *SearchService) { s.siteConfig = r }
}

// SetFeedbackReader attaches the per-chunk feedback aggregate reader used by
// the retrieval-time boost. Safe to leave unset (boost stays off).
func (s *SearchService) SetFeedbackReader(fr FeedbackReader) { s.feedback = fr }

// WithChunkService attaches the ChunkService used for Phase 3 §D
// retrieval-time parent-content lookup. When omitted the parent swap is
// a no-op (legacy flat behaviour for rows with NULL parent_chunk_id is
// unaffected; rows with non-nil parent_chunk_id keep their child content
// in the LLM context — a soft degradation but never a search-time error).
func WithChunkService(c *ChunkService) Option {
	return func(s *SearchService) { s.chunkSvc = c }
}

// WithQueryCache attaches a QueryCache for semantic-similarity result
// reuse. Optional — when nil the search pipeline runs unchanged.
func WithQueryCache(qc *QueryCache) Option {
	return func(s *SearchService) { s.queryCache = qc }
}

// CloneWithSiteConfigReader returns a new SearchService that shares every
// backing dependency (DB pools, AI resolver, embedding/chunk/hype/query caches)
// but reads site_config through r instead of the original reader. The clone
// gets fresh sync primitives (sync.Once, singleflight.Group) and an empty
// config cache, so it is independent and race-free.
//
// Used by the chat handler to apply per-KB config overrides on a request-local
// instance without mutating the process-wide shared SearchService (mirrors the
// eval runner's private-SearchService pattern).
func (s *SearchService) CloneWithSiteConfigReader(r SiteConfigReader) *SearchService {
	return &SearchService{
		vectorDB:       s.vectorDB,
		mainDB:         s.mainDB,
		aiResolver:     s.aiResolver,
		siteConfig:     r,
		embeddingCache: s.embeddingCache,
		chunkSvc:       s.chunkSvc,
		hype:           s.hype,
		queryCache:     s.queryCache,
		// rerankDefaultNoticeOnce, kbTableCache, siteConfigCache, siteConfigSF,
		// kbLangCachePtr, kbLangSF: zero values — fresh, independent caches.
	}
}

// NewSearchService creates a SearchService backed by the given connection
// pools and AI config resolver. Production callers should pass both
// WithEmbeddingCache and WithSiteConfigReader; tests may omit them.
func NewSearchService(vectorDB, mainDB *pgxpool.Pool, aiResolver *ai.ConfigResolver, opts ...Option) *SearchService {
	s := &SearchService{
		vectorDB:   vectorDB,
		mainDB:     mainDB,
		aiResolver: aiResolver,
		hype:       NewHyPEStore(vectorDB),
	}
	for _, opt := range opts {
		opt(s)
	}
	return s
}

// InvalidateQueryCache nukes all query_cache entries for the given KB.
// Called by file-mutation paths (ingestion completion, file deletion,
// re-ingestion) to prevent serving stale cached results. No-op if the
// service was constructed without a QueryCache (the dependency is
// optional, so callers that don't have one wired pay nothing). Errors
// are returned to the caller; the cache is best-effort and the TTL
// fallback (24h default) eventually corrects any missed invalidation.
// ExpandNeighbors is a method-flavoured wrapper around the package-level
// ExpandNeighbors func so chat orchestrators can call it through the
// Searcher interface without leaking the unexported NeighborFetcher contract.
func (s *SearchService) ExpandNeighbors(ctx context.Context, chunks []SearchChunk, windowSize int, tableName, kbID string) []SearchChunk {
	return ExpandNeighbors(ctx, chunks, windowSize, s, tableName, kbID)
}

func (s *SearchService) InvalidateQueryCache(ctx context.Context, kbID string) error {
	if s.queryCache == nil {
		return nil
	}
	return s.queryCache.Invalidate(ctx, kbID)
}

