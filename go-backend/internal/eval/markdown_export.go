// ExportSingleRunMarkdown renders a single eval run as a markdown document.
// The output is deterministic: same inputs → byte-identical output.
// If the run has no report (queued/running/failed), only the header and status
// section are emitted — no aggregate or question sections.
func ExportSingleRunMarkdown(r Run) string {
	var b strings.Builder

	labelOrID := runLabel(r)

	fmt.Fprintf(&b, "# Eval run: %s\n\n", labelOrID)

	// Metadata block.
	fmt.Fprintf(&b, "- **ID:** `%s`\n", r.ID)
	fmt.Fprintf(&b, "- **Label:** %s\n", labelDisplay(r.Label))
	fmt.Fprintf(&b, "- **Started:** %s\n", formatStartedAt(r.StartedAt))
	fmt.Fprintf(&b, "- **Finished:** %s\n", formatFinishedAt(r.FinishedAt))
	fmt.Fprintf(&b, "- **Status:** %s\n", r.Status)
	fmt.Fprintf(&b, "- **KB:** `%s`\n", r.KBID)
	fmt.Fprintf(&b, "- **Judge enabled:** %s\n", checkmark(r.JudgeEnabled))
	fmt.Fprintf(&b, "- **Fixture hash:** `%s`\n", hashPrefix(r.FixtureHash))

	// Parse report — if unavailable, stop here.
	rep, ok := parseReport(r.Report)
	if !ok {
		b.WriteString("\n*Run has not completed — no aggregate or question data available.*\n")
		if r.ErrorMessage != "" {
			fmt.Fprintf(&b, "\n**Error:** %s\n", r.ErrorMessage)
		}
		b.WriteString("\n")
		return b.String()
	}

	// Config snapshot section.
	b.WriteString("\n## Config snapshot\n\n")
	writeConfigTable(&b, r.ConfigSnapshot)

	// Aggregate section.
	fmt.Fprintf(&b, "\n## Aggregate (k=%d)\n\n", rep.K)
	b.WriteString("| route | n | recall | precision | MRR | nDCG |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|\n")
	routes := sortedRoutes(rep.RouteAggregates)
	for _, route := range routes {
		agg := rep.RouteAggregates[route]
		fmt.Fprintf(&b, "| `%s` | %d | %.3f | %.3f | %.3f | %.3f |\n",
			route, agg.Count, agg.MeanRecall, agg.MeanPrecision, agg.MRR, agg.MeanNDCG)
	}
	// Overall row always last.
	a := rep.Aggregate
	fmt.Fprintf(&b, "| **overall** | %d | %.3f | %.3f | %.3f | %.3f |\n",
		a.Count, a.MeanRecall, a.MeanPrecision, a.MRR, a.MeanNDCG)

	if len(rep.OrchestratorAggregates) > 0 {
		b.WriteString("\n## Per orchestrator\n\n")
		b.WriteString("| orchestrator | n | recall | precision | MRR | nDCG |\n")
		b.WriteString("|---|---:|---:|---:|---:|---:|\n")
		orchs := sortedRoutes(rep.OrchestratorAggregates)
		for _, o := range orchs {
			agg := rep.OrchestratorAggregates[o]
			label := o
			if label == "" {
				label = "unlabeled"
			}
			fmt.Fprintf(&b, "| `%s` | %d | %.3f | %.3f | %.3f | %.3f |\n",
				label, agg.Count, agg.MeanRecall, agg.MeanPrecision, agg.MRR, agg.MeanNDCG)
		}
	}

	// Top / bottom 5.
	top, bottom := topBottomQuestions(rep.Questions, 5)

	b.WriteString("\n## Top 5 questions (by recall@k)\n\n")
	if len(top) == 0 {
		b.WriteString("*(no questions)*\n")
	} else {
		for _, qr := range top {
			fmt.Fprintf(&b, "- `%s` [%s]: recall %.3f — *\"%s\"*\n",
				qr.Question.ID,
				routeLabel(qr.Question.QueryType),
				qr.Metrics.RecallAtK,
				truncateQuestion(qr.Question.Question))
		}
	}

	b.WriteString("\n## Bottom 5 questions (by recall@k)\n\n")
	if len(bottom) == 0 {
		b.WriteString("*(no questions)*\n")
	} else {
		for _, qr := range bottom {
			fmt.Fprintf(&b, "- `%s` [%s]: recall %.3f — *\"%s\"*\n",
				qr.Question.ID,
				routeLabel(qr.Question.QueryType),
				qr.Metrics.RecallAtK,
				truncateQuestion(qr.Question.Question))
		}
	}

	b.WriteString("\n---\n\n")
	b.WriteString("*Generated by JustRAG admin eval.*\n")

	return b.String()
}

// ExportCompareMarkdown renders a comparison of two eval runs as a markdown
// document. The output is deterministic: same inputs → byte-identical output.
// If either run has no report, a note is emitted in place of the aggregate and
// question sections.
func ExportCompareMarkdown(a, b Run) string {
	var sb strings.Builder

	aLabel := runLabel(a)
	bLabel := runLabel(b)
	fmt.Fprintf(&sb, "# Eval delta: run %s → run %s\n\n", aLabel, bLabel)

	// Run metadata lines.
	fmt.Fprintf(&sb, "- **Run A:** `%s` — %s — started %s — KB `%s` — judge %s\n",
		a.ID, labelDisplay(a.Label), formatStartedAt(a.StartedAt), a.KBID, checkmark(a.JudgeEnabled))
	fmt.Fprintf(&sb, "- **Run B:** `%s` — %s — started %s — KB `%s` — judge %s\n",
		b.ID, labelDisplay(b.Label), formatStartedAt(b.StartedAt), b.KBID, checkmark(b.JudgeEnabled))
	fmt.Fprintf(&sb, "- **Fixture hash A:** `%s`\n", hashPrefix(a.FixtureHash))
	fmt.Fprintf(&sb, "- **Fixture hash B:** `%s`\n", hashPrefix(b.FixtureHash))

	if a.FixtureHash == b.FixtureHash {
		sb.WriteString("- **Comparable:** yes\n")
	} else {
		sb.WriteString("- **Comparable:** NO — fixture hashes differ, results not strictly comparable\n")
	}

	// Config diff section.
	sb.WriteString("\n## Config diff\n\n")
	sb.WriteString("Only keys whose values differ between the two snapshots appear here. " +
		"Keys present in only one snapshot show as `null` on the other side.\n\n")
	writeConfigDiffTable(&sb, a.ConfigSnapshot, b.ConfigSnapshot)

	// Aggregate delta section — requires both reports.
	repA, okA := parseReport(a.Report)
	repB, okB := parseReport(b.Report)

	sb.WriteString("\n## Aggregate delta (B − A)\n\n")
	if !okA || !okB {
		sb.WriteString("*")
		if !okA && !okB {
			sb.WriteString("Neither run A nor run B has completed — no aggregate data available.")
		} else if !okA {
			sb.WriteString("Run A has not completed — aggregate delta unavailable.")
		} else {
			sb.WriteString("Run B has not completed — aggregate delta unavailable.")
		}
		sb.WriteString("*\n")
	} else {
		writeAggregateDeltaTable(&sb, repA, repB)
	}

	// Notable question changes section.
	sb.WriteString("\n## Notable question changes\n\n")
	if !okA || !okB {
		sb.WriteString("*Question-level comparison unavailable — one or both runs have not completed.*\n")
	} else {
		writeNotableChanges(&sb, repA, repB)
	}

	sb.WriteString("\n---\n\n")
	sb.WriteString("*Generated by JustRAG admin eval — see " +
		"`docs/superpowers/specs/2026-04-23-in-app-eval-runner-design.md` " +
		"for the canonical format definition.*\n")

	return sb.String()
}

