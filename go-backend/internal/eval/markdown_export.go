// writeConfigTable renders a single-column config snapshot table sorted by key.
func writeConfigTable(b *strings.Builder, raw json.RawMessage) {
	keys, vals := parseConfigSnapshot(raw)

	b.WriteString("| key | value |\n")
	b.WriteString("|---|---|\n")
	for _, k := range keys {
		v := vals[k]
		b.WriteString("| `")
		b.WriteString(k)
		b.WriteString("` | ")
		b.WriteString(formatConfigVal(v))
		b.WriteString(" |\n")
	}
}

// writeConfigDiffTable renders the two-column diff table (only differing keys).
func writeConfigDiffTable(b *strings.Builder, rawA, rawB json.RawMessage) {
	_, valsA := parseConfigSnapshot(rawA)
	_, valsB := parseConfigSnapshot(rawB)

	// Collect all keys that appear in either snapshot.
	allKeys := mergedKeys(valsA, valsB)

	// Filter to keys where values differ (or one side is missing).
	type diffRow struct {
		key string
		a   *string
		b   *string
	}
	var diffs []diffRow
	for _, k := range allKeys {
		va, hasA := valsA[k]
		vb, hasB := valsB[k]
		// Treat missing key as nil.
		var pa, pb *string
		if hasA {
			pa = va
		}
		if hasB {
			pb = vb
		}
		if configValEqual(pa, pb) {
			continue
		}
		diffs = append(diffs, diffRow{key: k, a: pa, b: pb})
	}

	if len(diffs) == 0 {
		b.WriteString("*(no retrieval-relevant config differences)*\n")
		return
	}

	b.WriteString("| key | A | B |\n")
	b.WriteString("|---|---|---|\n")
	for _, d := range diffs {
		b.WriteString("| `")
		b.WriteString(d.key)
		b.WriteString("` | ")
		b.WriteString(formatConfigVal(d.a))
		b.WriteString(" | ")
		b.WriteString(formatConfigVal(d.b))
		b.WriteString(" |\n")
	}
}

// writeAggregateDeltaTable renders the delta table.
// Route rows are alphabetically sorted; "overall" is always last.
func writeAggregateDeltaTable(b *strings.Builder, repA, repB Report) {
	deltas := ComputeRouteDeltas(repA, repB)

	b.WriteString("| route | n_B | recall Δ | precision Δ | MRR Δ | nDCG Δ |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|\n")

	routes := make([]string, 0, len(deltas))
	for r := range deltas {
		routes = append(routes, r)
	}
	slices.Sort(routes)

	for _, route := range routes {
		d := deltas[route]
		fmt.Fprintf(b, "| `%s` | %d | %+.3f | %+.3f | %+.3f | %+.3f |\n",
			route, d.Count,
			d.RecallDelta, d.PrecisionDelta, d.MRRDelta, d.NDCGDelta)
	}

	// Overall row.
	aAgg := repA.Aggregate
	bAgg := repB.Aggregate
	fmt.Fprintf(b, "| **overall** | %d | %+.3f | %+.3f | %+.3f | %+.3f |\n",
		bAgg.Count,
		bAgg.MeanRecall-aAgg.MeanRecall,
		bAgg.MeanPrecision-aAgg.MeanPrecision,
		bAgg.MRR-aAgg.MRR,
		bAgg.MeanNDCG-aAgg.MeanNDCG)
}

// writeNotableChanges renders the improved/regressed question lists.
func writeNotableChanges(b *strings.Builder, repA, repB Report) {
	// Build recall-by-question-id maps.
	recallA := make(map[string]float64, len(repA.Questions))
	for _, qr := range repA.Questions {
		recallA[qr.Question.ID] = qr.Metrics.RecallAtK
	}
	recallB := make(map[string]float64, len(repB.Questions))
	textB := make(map[string]string, len(repB.Questions))
	typeB := make(map[string]string, len(repB.Questions))
	for _, qr := range repB.Questions {
		recallB[qr.Question.ID] = qr.Metrics.RecallAtK
		textB[qr.Question.ID] = qr.Question.Question
		typeB[qr.Question.ID] = qr.Question.QueryType
	}

	type qChange struct {
		id    string
		qtype string
		text  string
		from  float64
		to    float64
		delta float64
	}

	var improved, regressed []qChange
	for id, rb := range recallB {
		ra, exists := recallA[id]
		if !exists {
			continue // question only in B, skip
		}
		delta := rb - ra
		if delta > 1e-9 {
			improved = append(improved, qChange{
				id: id, qtype: typeB[id], text: textB[id],
				from: ra, to: rb, delta: delta,
			})
		} else if delta < -1e-9 {
			regressed = append(regressed, qChange{
				id: id, qtype: typeB[id], text: textB[id],
				from: ra, to: rb, delta: delta,
			})
		}
	}

	// Sort improved: by delta desc, then by id asc (tie-break).
	slices.SortFunc(improved, func(a, b qChange) int {
		if math.Abs(a.delta-b.delta) > 1e-12 {
			return cmp.Compare(b.delta, a.delta)
		}
		return cmp.Compare(a.id, b.id)
	})
	// Sort regressed: by |delta| desc (most negative first), then by id asc.
	slices.SortFunc(regressed, func(a, b qChange) int {
		ai, bj := math.Abs(a.delta), math.Abs(b.delta)
		if math.Abs(ai-bj) > 1e-12 {
			return cmp.Compare(bj, ai)
		}
		return cmp.Compare(a.id, b.id)
	})

	if len(improved) > 5 {
		improved = improved[:5]
	}
	if len(regressed) > 5 {
		regressed = regressed[:5]
	}

	b.WriteString("**Improved (top 5 by recall@10 gain, B vs A):**\n")
	if len(improved) == 0 {
		b.WriteString("*(no notable changes)*\n")
	} else {
		for _, c := range improved {
			fmt.Fprintf(b, "- `%s` [%s]: %.3f → %.3f (Δ %+.3f) — *\"%s\"*\n",
				c.id, routeLabel(c.qtype), c.from, c.to, c.delta, truncateQuestion(c.text))
		}
	}

	b.WriteString("\n**Regressed (top 5 by recall@10 loss, B vs A):**\n")
	if len(regressed) == 0 {
		b.WriteString("*(no notable changes)*\n")
	} else {
		for _, c := range regressed {
			fmt.Fprintf(b, "- `%s` [%s]: %.3f → %.3f (Δ %+.3f) — *\"%s\"*\n",
				c.id, routeLabel(c.qtype), c.from, c.to, c.delta, truncateQuestion(c.text))
		}
	}
}

