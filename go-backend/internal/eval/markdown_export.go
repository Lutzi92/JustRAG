// parseReport tries to unmarshal the run's Report JSON into a Report struct.
// Returns (zero, false) when the report is empty or unparseable.
func parseReport(raw json.RawMessage) (Report, bool) {
	if len(raw) == 0 {
		return Report{}, false
	}
	var rep Report
	if err := json.Unmarshal(raw, &rep); err != nil {
		return Report{}, false
	}
	return rep, true
}

// parseConfigSnapshot unmarshals the snapshot JSON into a key→*string map.
// Returns the sorted key slice and the values map.
// A missing or unparseable snapshot yields an empty map.
func parseConfigSnapshot(raw json.RawMessage) ([]string, map[string]*string) {
	m := make(map[string]*string)
	if len(raw) > 0 {
		_ = json.Unmarshal(raw, &m)
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys, m
}

// mergedKeys returns a sorted slice of all keys present in either map.
func mergedKeys(a, b map[string]*string) []string {
	seen := make(map[string]struct{}, len(a)+len(b))
	for k := range a {
		seen[k] = struct{}{}
	}
	for k := range b {
		seen[k] = struct{}{}
	}
	out := make([]string, 0, len(seen))
	for k := range seen {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}

// configValEqual compares two *string config values (nil = absent/null).
func configValEqual(a, b *string) bool {
	if a == nil && b == nil {
		return true
	}
	if a == nil || b == nil {
		return false
	}
	return *a == *b
}

// formatConfigVal renders a *string config value for markdown table cells.
func formatConfigVal(v *string) string {
	if v == nil {
		return "`null`"
	}
	return fmt.Sprintf("`%s`", *v)
}

// runLabel returns the label if set, otherwise the UUID string.
func runLabel(r Run) string {
	if r.Label != "" {
		return r.Label
	}
	return r.ID.String()
}

// labelDisplay returns the label for display, or "(no label)".
func labelDisplay(label string) string {
	if label != "" {
		return label
	}
	return "(no label)"
}

// checkmark returns ✓ for true, ✗ for false.
func checkmark(b bool) string {
	if b {
		return "✓"
	}
	return "✗"
}

// hashPrefix returns the first 12 hex chars of the hash, or "(none)" when empty.
func hashPrefix(h string) string {
	if len(h) == 0 {
		return "(none)"
	}
	if len(h) > 12 {
		return h[:12]
	}
	return h
}

// formatStartedAt formats a *time.Time as ISO-8601 UTC, or "(not started)" when nil.
func formatStartedAt(t *time.Time) string {
	if t == nil {
		return "(not started)"
	}
	return t.UTC().Format("2006-01-02T15:04:05Z")
}

// formatFinishedAt formats a *time.Time as ISO-8601 UTC, or "(still running)" when nil.
func formatFinishedAt(t *time.Time) string {
	if t == nil {
		return "(still running)"
	}
	return t.UTC().Format("2006-01-02T15:04:05Z")
}

// routeLabel returns the query type label, defaulting to "unlabeled".
func routeLabel(qt string) string {
	if qt == "" {
		return "unlabeled"
	}
	return qt
}

// truncateQuestion truncates question text to ≤60 chars and strips markdown
// special characters (* and backtick) to prevent rendering glitches.
func truncateQuestion(s string) string {
	// Strip * and backtick.
	s = strings.ReplaceAll(s, "*", "")
	s = strings.ReplaceAll(s, "`", "")
	// Truncate at ≤60 runes.
	runes := []rune(s)
	if len(runes) > 60 {
		return string(runes[:60]) + "…"
	}
	return s
}

// sortedRoutes returns the route names sorted alphabetically.
func sortedRoutes(m map[string]AggregateMetrics) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}

// topBottomQuestions returns the top and bottom N questions by recall@k.
// Top: sorted by recall desc, ties broken by question ID asc.
// Bottom: sorted by recall asc, ties broken by question ID asc.
// Errored questions (with Error != "") are excluded.
func topBottomQuestions(questions []QuestionReport, n int) (top, bottom []QuestionReport) {
	// Filter out errored questions.
	valid := make([]QuestionReport, 0, len(questions))
	for _, q := range questions {
		if q.Error == "" {
			valid = append(valid, q)
		}
	}

	if len(valid) == 0 {
		return nil, nil
	}

	// Sort for top: descending recall, then ascending ID.
	sorted := make([]QuestionReport, len(valid))
	copy(sorted, valid)
	slices.SortFunc(sorted, func(a, b QuestionReport) int {
		ra, rb := a.Metrics.RecallAtK, b.Metrics.RecallAtK
		if math.Abs(ra-rb) > 1e-12 {
			return cmp.Compare(rb, ra)
		}
		return cmp.Compare(a.Question.ID, b.Question.ID)
	})

	if len(sorted) <= n {
		top = sorted
	} else {
		top = sorted[:n]
	}

	// Sort for bottom: ascending recall, then ascending ID.
	bottomSorted := make([]QuestionReport, len(valid))
	copy(bottomSorted, valid)
	slices.SortFunc(bottomSorted, func(a, b QuestionReport) int {
		ra, rb := a.Metrics.RecallAtK, b.Metrics.RecallAtK
		if math.Abs(ra-rb) > 1e-12 {
			return cmp.Compare(ra, rb)
		}
		return cmp.Compare(a.Question.ID, b.Question.ID)
	})

	if len(bottomSorted) <= n {
		bottom = bottomSorted
	} else {
		bottom = bottomSorted[:n]
	}

	return top, bottom
}
